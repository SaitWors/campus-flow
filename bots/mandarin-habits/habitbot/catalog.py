def make_goals(day, start_day, track, difficulty):
    index = max(0, (date.fromisoformat(day) - date.fromisoformat(start_day)).days)
    factor = {'light': 0.6, 'normal': 1.0, 'hard': 1.5}[difficulty]
    tools = ('Используй Java: JDK, коллекции, при проверках JUnit.' if track == 'java'
             else 'Используй Python: стандартную библиотеку, при проверках unittest или pytest.')
    result = []
    for kind, catalog, minutes, xp, coins in [('sport', SPORT, 20, 30, 20), ('code', CODE, 30, 50, 30)]:
        title, details = catalog[index % len(catalog)]
        if kind == 'code':
            details += ' ' + tools + ' Если задача уже сделана — улучши тот же небольшой проект.'
        result.append(dict(day=day, kind=kind, title=title, details=details,
                           minutes=max(5, round(minutes * factor)), xp=round(xp * factor),
                           coins=round(coins * factor)))
    return result
